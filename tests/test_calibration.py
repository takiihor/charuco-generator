@pytest.fixture(scope="module")
def calibration_artifacts(tmp_path_factory):
    directory = tmp_path_factory.mktemp("calibration")
    config = calibration_config(CalibrationTarget(dpi=200), str(directory))
    report = generate(config)
    return directory, config, report


def test_default_is_the_conventional_5x7_board_filling_a4(calibration_artifacts):
    _, config, report = calibration_artifacts
    geometry = config.geometry
    assert (geometry.squares_x, geometry.squares_y) == (5, 7)
    assert (geometry.square_length_mm, geometry.marker_length_mm) == (30.0, 22.5)
    assert geometry.dictionary == "DICT_6X6_250"
    assert config.printing.page_size == "A4"
    assert [board.name for board in config.boards] == [BOARD_NAME]
    assert config.boards[0].marker_ids == tuple(range(17))
    assert report["passed"]
    assert report["boards"][0]["detected_marker_count"] == 17
    assert report["boards"][0]["detected_charuco_corner_count"] == 24
    sheet = next(pdf for pdf in report["pdfs"] if pdf["input"] == "calibration_charuco.pdf")
    assert sheet["page_count"] == 1
    assert sheet["page_dimensions_mm"] == [210.0, 297.0]
    assert sheet["patterns"][0]["transformed_form_bbox_mm_xywh"][2:] == pytest.approx([150, 210], abs=0.001)


def test_calibration_dictionary_cannot_be_read_as_localization_markers(calibration_artifacts):
    directory, _, _ = calibration_artifacts
    image = cv2.imread(str(directory / "calibration_charuco.png"), cv2.IMREAD_GRAYSCALE)
    _, ids, _ = cv2.aruco.ArucoDetector(dictionary_for("DICT_5X5_100")).detectMarkers(image)
    assert ids is None


def test_landscape_and_page_fill():
    landscape = calibration_config(CalibrationTarget(landscape=True))
    assert landscape.printing.page_size == "297x210"
    assert (landscape.geometry.squares_x, landscape.geometry.squares_y) == (8, 4)
    smaller = calibration_config(CalibrationTarget(square_length_mm=20))
    assert (smaller.geometry.squares_x, smaller.geometry.squares_y) == (7, 10)
    a3 = calibration_config(CalibrationTarget(page_size="A3"))
    assert (a3.geometry.squares_x, a3.geometry.squares_y) == (8, 11)


@pytest.mark.parametrize(("target", "message"), [
    (CalibrationTarget(squares=(6, 8)), "exceeds"),
    (CalibrationTarget(squares=(2, 5)), "at least 3 x 3"),
    (CalibrationTarget(square_length_mm=60), "at least 3 x 3"),
    (CalibrationTarget(first_id=240), "first ID must be 0..233"),
    (CalibrationTarget(dictionary="DICT_4X4_50", square_length_mm=10), "holds only 50"),
    (CalibrationTarget(square_length_mm=float("nan")), "finite positive"),
])
def test_impossible_targets_are_explained(target, message):
    with pytest.raises(ConfigError, match=message):
        calibration_config(target)


def test_opencv_snippet_rebuilds_the_same_board():
    for target in (CalibrationTarget(), CalibrationTarget(first_id=50)):
        config = calibration_config(target)
        code = opencv_board_code(config)
        assert ("np.arange(50, 67" in code) == (target.first_id == 50)
        board = eval(code, {"cv2": cv2, "np": np})  # snippet generated by this program, not user input
        assert board.getChessboardSize() == (5, 7)
        assert board.getSquareLength() == pytest.approx(0.03)
        assert board.getMarkerLength() == pytest.approx(0.0225)
        assert board.getIds().ravel().tolist() == list(config.boards[0].marker_ids)


def test_cli_generates_verifies_and_validates(tmp_path, capsys):
    target = tmp_path / "calib"
    assert main(["calibration", "--landscape", "--dpi", "150", "--output-dir", str(target)]) == 0
    out = capsys.readouterr().out
    assert "8 x 4 squares of 30 mm" in out and "OpenCV: cv2.aruco.CharucoBoard((8, 4)" in out
    assert "legacy pattern" in out  # four rows: layout differs in OpenCV < 4.6
    manifest = target / "board_manifest.json"
    assert main(["verify", "--manifest", str(manifest)]) == 0
    capsys.readouterr()
    assert main(["validate", "--board", BOARD_NAME, "--manifest", str(manifest),
                 "--input", str(target / "calibration_charuco.png")]) == 0
    assert json.loads(capsys.readouterr().out)["mode"] == "synthetic"


def test_cli_rejects_oversized_grid_without_publishing(tmp_path, capsys):
    target = tmp_path / "calib"
    assert main(["calibration", "--squares", "6x8", "--output-dir", str(target)]) == 2
    assert "exceeds" in capsys.readouterr().err
    assert not target.exists()


def test_regeneration_into_the_same_folder_is_allowed(calibration_artifacts, tmp_path):
    directory, config, _ = calibration_artifacts
    shutil.copytree(directory, tmp_path, dirs_exist_ok=True)
    assert generate(replace(config, output_dir=str(tmp_path)))["passed"]
    assert load_manifest(tmp_path / "board_manifest.json")["boards"][0]["name"] == BOARD_NAME


@pytest.mark.skipif(shutil.which("pdftoppm") is None, reason="Poppler optional PDF render integration test")
def test_printed_vector_sheet_detects_every_corner(calibration_artifacts, tmp_path):
    directory, config, _ = calibration_artifacts
    subprocess.run(["pdftoppm", "-r", "100", "-png", str(directory / "calibration_charuco.pdf"), str(tmp_path / "page")],
                   check=True, capture_output=True)
    (page,) = sorted(tmp_path.glob("page*.png"))
    geometry = config.geometry
    board = cv2.aruco.CharucoBoard((geometry.squares_x, geometry.squares_y), geometry.square_length_mm / 1000,
                                   geometry.marker_length_mm / 1000, dictionary_for(geometry.dictionary))
    _, corner_ids, _, marker_ids = cv2.aruco.CharucoDetector(board).detectBoard(
        cv2.imread(str(page), cv2.IMREAD_GRAYSCALE))
    assert sorted(corner_ids.ravel().tolist()) == list(range(geometry.corner_count))
    assert sorted(marker_ids.ravel().tolist()) == list(range(geometry.marker_count))


@pytest.mark.skipif(sys.platform == "win32", reason="Bash launcher")
def test_shell_launcher_from_another_directory(tmp_path):
    output = tmp_path / "calibration board"
    result = subprocess.run([str(ROOT / "generate_calibration.sh"), "--dpi", "150", "--output-dir", str(output)],
                            cwd=tmp_path, stdin=subprocess.DEVNULL, capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stderr
    assert "5 x 7 squares of 30 mm" in result.stdout
    assert (output / "calibration_A4.pdf").is_file()
