"""Two-stage tank localisation markers: every set, one ID plan, checked for collisions.

Stage 1 (coarse): the AGV camera, 500-800 mm from the tanks, reads one large marker per tank and
guides the UR10e. Stage 2 (fine): the UR10e wrist camera, about 300 mm away, reads one small
ChArUco board per tank for the precise coordinate. Each stage has its own calibration board.

Every set is generated by the ordinary, verified generators (aruco, tank boards, calibration).
This module only fixes the plan, so sizes and ID blocks cannot drift apart between sets, and
refuses to generate if two sets that may be seen together share a marker code. Same-size ArUco
dictionaries are one code family (DICT_5X5_250 repeats DICT_5X5_100's codes), so collisions are
checked per family, not per dictionary name.
"""
import json
import re
from dataclasses import dataclass
from pathlib import Path

from .aruco import ArucoConfig, generate_aruco
from .calibration import CalibrationTarget, calibration_config
from .config import Config, ConfigError, Printing, load_config
from .generator import generate, write_json
from .tanks import TankSetTarget, tank_config, tank_table

DEFAULT_TANKS = 16
STAGE2_DICTIONARY = "DICT_6X6_250"
#: DICT_6X6_250 blocks: 0-16 the A4 calibration board, then stage-2 tank boards, then the two
#: stage calibration boards. Distinct IDs keep boards of different sizes from ever being confused.
STAGE2_FIRST_ID = 17


@dataclass(frozen=True)
class SetPlan:
    folder: str
    stage: str
    camera: str
    purpose: str


SETS = {
    "stage1_aruco_realsense": SetPlan("stage1_aruco_realsense", "1", "AGV camera (RealSense), 500-800 mm",
                                      "Coarse tank identity and position; marker ID = tank number"),
    "stage2_charuco_basler_32mm": SetPlan("stage2_charuco_basler_32mm", "2", "Wrist camera (Basler), ~300 mm",
                                          "Fine tank coordinate; production size"),
    "stage2_charuco_realsense_80mm": SetPlan("stage2_charuco_realsense_80mm", "2", "Wrist camera (RealSense), ~300 mm",
                                             "Same targets as the 32 mm set, enlarged for RealSense tests"),
    "calibration_stage1": SetPlan("calibration_stage1", "1", "AGV camera, calibrate at 500-650 mm",
                                  "AGV camera intrinsics and AGV camera to UR10e base (360 x 200 mm, A3)"),
    "calibration_stage2": SetPlan("calibration_stage2", "2", "Wrist camera (Basler), ~300 mm",
                                  "Wrist camera intrinsics and hand-eye"),
}
#: Size variants of the same physical targets: they intentionally share codes, and must never be
#: installed at the same time.
SIZE_VARIANTS = {frozenset({"stage2_charuco_basler_32mm", "stage2_charuco_realsense_80mm"})}


def code_family(dictionary: str) -> str:
    match = re.fullmatch(r"DICT_(\d)X\1_\d+", dictionary)
    return f"{match.group(1)}x{match.group(1)}" if match else dictionary


def stage2_ids_end(tanks: int) -> int:
    return STAGE2_FIRST_ID + 8 * tanks


def configs(tanks: int, output_dir: Path, dpi: int | None = None) -> dict:
    """Every set's generator configuration, derived from the plan."""
    if type(tanks) is not int or not 1 <= tanks <= 24:
        # 24 tanks x 8 IDs plus both calibration boards fill DICT_6X6_250 up to ID 247 of 249.
        raise ConfigError("The two-stage plan covers 1 to 24 tanks")
    # 9 x 5 squares of 40 mm (360 x 200 mm) on landscape A3: large enough for the AGV camera at 500-650 mm.
    calibration1 = calibration_config(CalibrationTarget(
        page_size="A3", landscape=True, square_length_mm=40.0, marker_length_mm=32.0, squares=(9, 5),
        dictionary=STAGE2_DICTIONARY, first_id=stage2_ids_end(tanks), dpi=dpi or 300, name="calibration_stage1"),
        str(output_dir / "calibration_stage1"))
    return {
        "stage1_aruco_realsense": ArucoConfig(
            "DICT_5X5_100", 150.0, 1, Printing(dpi or 300, "A4", 10.0, 10.0), tuple(range(1, tanks + 1))),
        "stage2_charuco_basler_32mm": tank_config(TankSetTarget(
            count=tanks, square_length_mm=8.0, dictionary=STAGE2_DICTIONARY, first_id=STAGE2_FIRST_ID,
            dpi=dpi or 600, white_margin_mm=5.0), str(output_dir / "stage2_charuco_basler_32mm")),
        "stage2_charuco_realsense_80mm": tank_config(TankSetTarget(
            count=tanks, square_length_mm=20.0, dictionary=STAGE2_DICTIONARY, first_id=STAGE2_FIRST_ID,
            dpi=dpi or 600), str(output_dir / "stage2_charuco_realsense_80mm")),
        "calibration_stage1": calibration1,
        # 5 x 7 squares of 15 mm (75 x 105 mm): fills most of the Basler + 12 mm view at 300 mm.
        "calibration_stage2": calibration_config(CalibrationTarget(
            square_length_mm=15.0, squares=(5, 7), dictionary=STAGE2_DICTIONARY,
            first_id=max(calibration1.boards[0].marker_ids) + 1, dpi=dpi or 600, name="calibration_stage2"),
            str(output_dir / "calibration_stage2")),
    }


def codes(config) -> tuple[str, set[int]]:
    if isinstance(config, ArucoConfig):
        return code_family(config.dictionary), set(config.marker_ids)
    return code_family(config.geometry.dictionary), {i for board in config.boards for i in board.marker_ids}


def check_collisions(plan: dict) -> None:
    names = list(plan)
    for index, first in enumerate(names):
        for second in names[index + 1:]:
            if frozenset({first, second}) in SIZE_VARIANTS:
                continue
            family_a, ids_a = codes(plan[first])
            family_b, ids_b = codes(plan[second])
            shared = sorted(ids_a & ids_b) if family_a == family_b else []
            if shared:
                raise ConfigError(f"{first} and {second} share {family_a} marker codes {shared[:8]}")


def existing_conflicts(plan: dict, boards_config: Path | None) -> list[str]:
    """Codes shared with the project's other boards (Front/Rear), which may also be in view."""
    if boards_config is None or not boards_config.is_file():
        return []
    other: Config = load_config(boards_config)
    family, ids = codes(other)
    warnings = []
    for name, config in plan.items():
        set_family, set_ids = codes(config)
        shared = sorted(ids & set_ids) if set_family == family else []
        if shared:
            boards = ", ".join(b.name for b in other.boards if set(b.marker_ids) & set_ids)
            warnings.append(f"{name} shares {family} codes {shared[0]}-{shared[-1]} with the {boards} board(s) in "
                            f"{boards_config}: never let both be seen by the same camera, or re-ID one of them")
    return warnings


def lookup(plan: dict) -> list[dict]:
    """Per tank: the stage-1 marker ID and the stage-2 board IDs."""
    stage1 = plan["stage1_aruco_realsense"].marker_ids
    rows = []
    for row, marker_id in zip(tank_table(plan["stage2_charuco_basler_32mm"]), stage1, strict=True):
        rows.append({"tank": row["tank"], "stage1_marker_id": marker_id, "stage2_board": row["board"],
                     "stage2_marker_ids": row["marker_ids"]})
    return rows


def describe(name: str, config) -> dict:
    meta = SETS[name]
    entry: dict[str, object] = {"folder": meta.folder, "stage": meta.stage, "camera": meta.camera,
                                "purpose": meta.purpose}
    if isinstance(config, ArucoConfig):
        ids = list(config.marker_ids)
        entry.update(kind="aruco", dictionary=config.dictionary, marker_mm=config.marker_length_mm,
                     ids=[ids[0], ids[-1]], manifest=f"{meta.folder}/aruco_manifest.json")
    else:
        g = config.geometry
        ids = sorted(i for board in config.boards for i in board.marker_ids)
        entry.update(kind="charuco", dictionary=g.dictionary, squares=[g.squares_x, g.squares_y],
                     square_mm=g.square_length_mm, marker_mm=g.marker_length_mm,
                     pattern_mm=list(g.pattern_mm), corners_per_board=g.corner_count, boards=len(config.boards),
                     ids=[ids[0], ids[-1]], manifest=f"{meta.folder}/board_manifest.json")
    return entry


def generate_plan(output_dir="output/two_stage", *, tanks: int = DEFAULT_TANKS, dpi: int | None = None,
                  clean: bool = False, boards_config: Path | None = None) -> dict:
    root = Path(output_dir)
    plan = configs(tanks, root, dpi)
    check_collisions(plan)  # before anything is written
    reports = {}
    for name, config in plan.items():
        if isinstance(config, ArucoConfig):
            reports[name] = generate_aruco(config, root / SETS[name].folder, clean=clean)
        else:
            reports[name] = generate(config, clean=clean)
    summary = {"schema_version": 1, "kind": "two_stage_marker_plan", "tanks": tanks,
               "sets": {name: describe(name, config) for name, config in plan.items()},
               "tank_lookup": lookup(plan),
               "warnings": existing_conflicts(plan, boards_config),
               "rules": [
                   "Any one marker of a tank's stage-2 board identifies the tank; its stage-1 marker ID is the tank "
                   "number. Act only when both stages agree.",
                   "The 32 mm and 80 mm stage-2 sets are the same targets at two sizes: install only one of them.",
                   "Calibrate each camera at its working focus; refocusing afterwards invalidates the calibration."]}
    write_json(root / "marker_plan.json", summary)
    return {"plan": summary, "reports": reports}


def load_plan(path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))
